"""Proof flags (Deyao, 2026-10-20): the proof view (/app/proof, the edge app's -ProofPage.tsx) steps through the stored
posts of chosen sources, one entry at a time, so Deyao can check each looks right; an entry that looks wrong gets a
flag with an optional note. A flag is the site's only write outside the AI routes: POST /app/proof/flag (web.py, sent
to the cluster by the yyc-edge Worker, approved accounts only). Open flags are listed on the monitor (the edge app
reads this table) and here, for Claude to fix them.

    python3 proof.py list [--all]           # open flags (--all: resolved ones too), newest first, as JSON lines
    python3 proof.py show ID                # one flag with the post as stored
    python3 proof.py resolve ID [NOTE…]     # mark a flag fixed (what was done)
    python3 proof.py delete ID              # remove a flag (a test flag)

Run with DATABASE_URL set (the cluster's Secret db-app, or role `app` through deploy/cluster/cluster.sh db-forward
from a session).
"""
import json, sys

import corpus

SCHEMA = """
CREATE TABLE IF NOT EXISTS proof_flags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id BIGINT REFERENCES posts(id) ON DELETE SET NULL,
  url TEXT NOT NULL, sid TEXT, note TEXT, email TEXT NOT NULL, at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ, resolved_note TEXT);
CREATE INDEX IF NOT EXISTS proof_flags_open ON proof_flags (at DESC) WHERE resolved_at IS NULL;
CREATE INDEX IF NOT EXISTS proof_flags_post ON proof_flags (post_id);
"""
NOTE_MAX = 2000
_ready = False


def ensure():
    """the table (created on first use; the edge app reads it with role yyc_edge, which has SELECT on every table role
    app makes through its default privileges)"""
    global _ready
    if not _ready:
        with corpus.lock("yyc proof_flags schema"):
            corpus.db().execute(SCHEMA)
        _ready = True


COLS = ("id, post_id, url, sid, note, email, to_char(at AT TIME ZONE 'Asia/Hong_Kong', 'YYYY-MM-DD\"T\"HH24:MI:SS') || "
        "'+08:00' AS at, to_char(resolved_at AT TIME ZONE 'Asia/Hong_Kong', 'YYYY-MM-DD\"T\"HH24:MI:SS') || '+08:00' "
        "AS resolved_at, resolved_note")


def add(post_id, note, email):
    """a flag on one stored post → the flag as stored. ValueError when the post doesn't exist"""
    if not email:
        raise ValueError("an approved account is needed")
    try:
        pid = int(post_id)
    except (TypeError, ValueError):
        raise ValueError("post id expected") from None
    note = (str(note or "")).strip()[:NOTE_MAX] or None
    ensure()
    r = corpus.db().execute("SELECT url, sid FROM posts WHERE id = %s", (pid,)).fetchone()
    if not r:
        raise ValueError("no such post")
    row = corpus.db().execute(f"INSERT INTO proof_flags (post_id, url, sid, note, email) VALUES (%s, %s, %s, %s, %s) "
                              f"RETURNING {COLS}", (pid, r["url"], r["sid"], note, email.lower())).fetchone()
    return dict(row)


def flags(open_only=True, post_id=None, limit=500):
    ensure()
    where, args = [], []
    if open_only:
        where.append("resolved_at IS NULL")
    if post_id is not None:
        where.append("post_id = %s")
        args.append(int(post_id))
    sql = f"SELECT {COLS} FROM proof_flags" + (" WHERE " + " AND ".join(where) if where else "") + \
        " ORDER BY id DESC LIMIT %s"
    return [dict(r) for r in corpus.db().execute(sql, (*args, limit)).fetchall()]


def resolve(flag_id, note=None):
    ensure()
    r = corpus.db().execute(f"UPDATE proof_flags SET resolved_at = now(), resolved_note = %s WHERE id = %s RETURNING {COLS}",
                            ((note or "").strip() or None, int(flag_id))).fetchone()
    return dict(r) if r else None


def delete(flag_id):
    ensure()
    return corpus.db().execute("DELETE FROM proof_flags WHERE id = %s", (int(flag_id),)).rowcount


def show(flag_id):
    ensure()
    f = corpus.db().execute(f"SELECT {COLS} FROM proof_flags WHERE id = %s", (int(flag_id),)).fetchone()
    if not f:
        return None
    post = corpus.db().execute("SELECT id, url, sid, source, website, title, author, published, seen, cached_at, "
                               "text_via, first_run, left(text, 4000) AS text FROM posts WHERE id = %s",
                               (f["post_id"],)).fetchone() if f["post_id"] else None
    return {"flag": dict(f), "post": dict(post) if post else None}


def main(argv):
    cmd = argv[0] if argv else ""
    if cmd == "list":
        for f in flags(open_only="--all" not in argv):
            print(json.dumps(f, ensure_ascii=False, default=str))
    elif cmd == "show" and len(argv) == 2:
        print(json.dumps(show(argv[1]), ensure_ascii=False, indent=1, default=str))
    elif cmd == "resolve" and len(argv) >= 2:
        print(json.dumps(resolve(argv[1], " ".join(argv[2:])), ensure_ascii=False, default=str))
    elif cmd == "delete" and len(argv) == 2:
        print(delete(argv[1]), "deleted")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
